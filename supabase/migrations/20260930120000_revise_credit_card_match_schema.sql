CREATE TABLE public.user_category_spend (
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    category_id BIGINT NOT NULL REFERENCES public.reward_categories(category_id) ON DELETE CASCADE,
    monthly_amount DECIMAL(10,2) NOT NULL CHECK (monthly_amount >= 0),
    UNIQUE (user_id, category_id)
);

CREATE TABLE public.user_filter_preferences (
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    filter_id BIGINT NOT NULL REFERENCES public.filters(filter_id) ON DELETE CASCADE,
    preference TEXT NOT NULL CHECK (preference IN ('want', 'avoid')),
    UNIQUE (user_id, filter_id)
);

-- Foreign-key indexes. Primary-key and UNIQUE indexes already cover
-- profiles.id, user_preferences.user_id, card_rewards.card_id,
-- card_filters.card_id, user_category_spend.user_id, and
-- user_filter_preferences.user_id as leading columns.
CREATE INDEX card_rewards_category_id_idx
    ON public.card_rewards (category_id);
CREATE INDEX recommendations_user_id_idx
    ON public.recommendations (user_id);
CREATE INDEX recommendations_card_id_idx
    ON public.recommendations (card_id);
CREATE INDEX card_filters_filter_id_idx
    ON public.card_filters (filter_id);
CREATE INDEX card_benefits_card_id_idx
    ON public.card_benefits (card_id);
CREATE INDEX user_category_spend_category_id_idx
    ON public.user_category_spend (category_id);
CREATE INDEX user_filter_preferences_filter_id_idx
    ON public.user_filter_preferences (filter_id);

