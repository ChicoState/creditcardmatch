-- Revise the initial Credit Card Match schema for Supabase Auth, extensible
-- filters, saved survey data, and owner-scoped row-level security.
--
-- This migration is intentionally additive to migration history. It migrates
-- an existing public.users row only when its email maps to exactly one
-- auth.users row; otherwise it stops before discarding legacy user data.

BEGIN;

-- Supabase Auth owns identity and email. Application-specific names live here.
CREATE TABLE public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    -- TODO(TBD): Decide whether first_name and last_name are required at sign-up.
    first_name VARCHAR(50),
    last_name VARCHAR(50)
);

-- Guard the one-time transition from the initial bigint user identifiers.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM public.users AS legacy_user
        LEFT JOIN auth.users AS auth_user
            ON LOWER(auth_user.email) = LOWER(legacy_user.email)
        GROUP BY legacy_user.user_id
        HAVING COUNT(auth_user.id) <> 1
    ) THEN
        RAISE EXCEPTION
            'Each public.users row must match exactly one auth.users email before this migration can run';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.users AS legacy_user
        JOIN auth.users AS auth_user
            ON LOWER(auth_user.email) = LOWER(legacy_user.email)
        GROUP BY auth_user.id
        HAVING COUNT(legacy_user.user_id) > 1
    ) THEN
        RAISE EXCEPTION
            'Multiple public.users rows map to the same auth.users row';
    END IF;
END;
$$;

INSERT INTO public.profiles (id, first_name, last_name)
SELECT auth_user.id, legacy_user.first_name, legacy_user.last_name
FROM public.users AS legacy_user
JOIN auth.users AS auth_user
    ON LOWER(auth_user.email) = LOWER(legacy_user.email);

ALTER TABLE public.user_preferences
    ADD COLUMN auth_user_id UUID;

ALTER TABLE public.recommendations
    ADD COLUMN auth_user_id UUID;

UPDATE public.user_preferences AS preference
SET auth_user_id = auth_user.id
FROM public.users AS legacy_user
JOIN auth.users AS auth_user
    ON LOWER(auth_user.email) = LOWER(legacy_user.email)
WHERE preference.user_id = legacy_user.user_id;

UPDATE public.recommendations AS recommendation
SET auth_user_id = auth_user.id
FROM public.users AS legacy_user
JOIN auth.users AS auth_user
    ON LOWER(auth_user.email) = LOWER(legacy_user.email)
WHERE recommendation.user_id = legacy_user.user_id;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM public.user_preferences
        WHERE auth_user_id IS NULL
    ) OR EXISTS (
        SELECT 1
        FROM public.recommendations
        WHERE auth_user_id IS NULL
    ) THEN
        RAISE EXCEPTION
            'All legacy user-owned rows must map to Supabase Auth before this migration can run';
    END IF;
END;
$$;

ALTER TABLE public.user_preferences
    ALTER COLUMN auth_user_id SET NOT NULL;
ALTER TABLE public.user_preferences
    DROP COLUMN user_id;
ALTER TABLE public.user_preferences
    RENAME COLUMN auth_user_id TO user_id;

ALTER TABLE public.user_preferences
    ADD CONSTRAINT user_preferences_user_id_key UNIQUE (user_id),
    ADD CONSTRAINT user_preferences_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES public.profiles(id) ON DELETE CASCADE;

ALTER TABLE public.recommendations
    ALTER COLUMN auth_user_id SET NOT NULL;
ALTER TABLE public.recommendations
    DROP COLUMN user_id;
ALTER TABLE public.recommendations
    RENAME COLUMN auth_user_id TO user_id;

ALTER TABLE public.recommendations
    ADD CONSTRAINT recommendations_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES public.profiles(id) ON DELETE CASCADE;

COMMENT ON TABLE public.recommendations IS
    'Reserved for future saved recommendations; unused in the MVP.';

DROP TABLE public.users;

-- URL-facing filter vocabulary. Filters are rows so the vocabulary can grow
-- without adding columns or changing application query shapes.
CREATE TABLE public.filters (
    filter_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE,
    label TEXT NOT NULL,
    description TEXT
);

CREATE TABLE public.card_filters (
    card_id BIGINT NOT NULL REFERENCES public.credit_cards(card_id) ON DELETE CASCADE,
    filter_id BIGINT NOT NULL REFERENCES public.filters(filter_id) ON DELETE CASCADE,
    PRIMARY KEY (card_id, filter_id)
);

INSERT INTO public.filters (slug, label, description)
VALUES
    ('popular-cards', 'Popular Cards', NULL),
    ('cashback', 'Cashback', NULL),
    ('new-to-credit', 'New-to-Credit', NULL);

ALTER TABLE public.credit_cards
    ADD COLUMN image_url TEXT,
    ADD COLUMN description TEXT,
    -- TODO(TBD): Confirm allowed reward_type values; candidates are cashback, points, and miles.
    ADD COLUMN reward_type TEXT,
    -- TODO(TBD): Define the allowed credit_level_required values.
    ADD COLUMN credit_level_required TEXT,
    ADD COLUMN source_url TEXT,
    ADD COLUMN last_verified_at TIMESTAMPTZ,
    ADD COLUMN is_verified BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE public.card_benefits (
    card_benefit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id BIGINT NOT NULL REFERENCES public.credit_cards(card_id) ON DELETE CASCADE,
    description TEXT NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0
);

ALTER TABLE public.card_rewards
    ADD CONSTRAINT card_rewards_card_id_category_id_key
        UNIQUE (card_id, category_id);

ALTER TABLE public.user_preferences
    -- TODO(TBD): Define the allowed income_range values.
    ADD COLUMN income_range TEXT;

-- TODO(TBD): Confirm the credit_score_range value for no credit history;
